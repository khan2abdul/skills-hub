#!/usr/bin/env python3
"""Build SKILLS.html - one page describing every shipped skill.

Port of tools/build-skill-page.ps1.

Reads tools/skill-page-data.json (hand-derived guidance) plus RATING.json
(scores) and emits a single self-contained HTML file. No dependencies, no
network, no build step beyond running this.

The static CSS/JS lives in tools/skill-page.template.html, extracted verbatim
from the PowerShell original, so the generated bytes match it exactly. Two
placeholders are filled per build:
  {{STAT_ITEMS}}       the header counters
  {{PHASE_SECTIONS}}   one <section> per phase, cards inside
"""
from __future__ import annotations

import argparse
import html
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import hubcommon as C  # noqa: E402

# Phases in the order a piece of work actually moves through them.
PHASE_ORDER = [
    "Always on", "Understand", "Research", "Spec", "Visualise", "Plan", "Build",
    "Debug", "Review", "Verify", "Finish", "Docs", "Ship", "Meta",
]
PHASE_BLURB = {
    "Always on": "Apply on every task, not at one point in the pipeline.",
    "Understand": "Turn a vague ask into a shared, explicit intent.",
    "Research": "Get the facts from primary sources before deciding anything.",
    "Spec": "Write down what will be built and why, before code exists.",
    "Visualise": "Turn a system or flow into a checked, explorable diagram.",
    "Plan": "Cut the work into slices and stress the plan while it is still cheap.",
    "Build": "Write the code, in tested increments.",
    "Debug": "Find the real cause instead of guessing at a symptom.",
    "Review": "Judge a change before it merges.",
    "Verify": "Produce evidence that it actually works.",
    "Finish": "Close the gap between working and good.",
    "Docs": "Write prose a stranger can act on.",
    "Ship": "Take it to the remote, or stop something destructive.",
    "Meta": "Change how the session itself runs.",
}


def esc(s) -> str:
    """Escape for HTML text and attribute context, matching the original's Esc()."""
    if s is None:
        return ""
    return (
        str(s).replace("&", "&amp;").replace("<", "&lt;")
        .replace(">", "&gt;").replace('"', "&quot;")
    )


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--hub-root", default="")
    ap.add_argument("--out-file", default="SKILLS.html")
    args = ap.parse_args(argv)

    script_dir = Path(__file__).resolve().parent
    hub_root = Path(args.hub_root) if args.hub_root else script_dir.parent

    data_path = script_dir / "skill-page-data.json"
    if not data_path.is_file():
        raise SystemExit(f"missing {data_path}")
    data = json.loads(C.read_text(data_path))
    if not isinstance(data, list):
        data = [data]

    ratings: dict[str, dict] = {}
    rating_path = hub_root / "RATING.json"
    if rating_path.is_file():
        for s in json.loads(C.read_text(rating_path)).get("skills", []):
            ratings[s["name"]] = s

    template_path = script_dir / "skill-page.template.html"
    if not template_path.is_file():
        raise SystemExit(f"missing {template_path}")
    template = C.read_text(template_path)

    gate_count = sum(1 for s in data if (s.get("gate") or {}).get("asks"))
    phases = len({s.get("phase") for s in data})

    stat_items = "\n".join([
        f"      <li><b>{len(data)}</b> skills</li>",
        f"      <li><b>{gate_count}</b> stop and ask first</li>",
        f"      <li><b>{len(data) - gate_count}</b> never interrupt</li>",
        f"      <li><b>{len(data)}</b> model-invocable</li>",
        f"      <li><b>{phases}</b> phases</li>",
    ])

    sections: list[str] = []
    for phase in PHASE_ORDER:
        items = [s for s in data if s.get("phase") == phase]
        if not items:
            continue
        phase_id = "".join(ch if (ch.isalnum() and ch.islower()) else "-"
                           for ch in phase.lower())
        # collapse runs of separators, then trim, matching -replace '[^a-z0-9]+','-'
        phase_id = "-".join(p for p in phase_id.split("-") if p)
        sections.append(f'<section class="phase" id="{phase_id}">')
        plural = "s" if len(items) != 1 else ""
        sections.append(f"  <h2>{phase} <span>{len(items)} skill{plural}</span></h2>")
        if phase in PHASE_BLURB:
            sections.append(f'  <p class="blurb">{esc(PHASE_BLURB[phase])}</p>')

        for s in items:
            r = ratings.get(s["name"])
            score = f"rating {r['score']} / {r['grade']}" if r else ""
            gate = s.get("gate") or {}
            haystack = " ".join([
                str(s.get("name")),
                str(s.get("summary")),
                " ".join(s.get("when") or []),
                " ".join(s.get("notWhen") or []),
                str(s.get("example")),
                str(s.get("phase")),
                str(gate.get("what")),
            ]).lower()
            gate_attr = "true" if gate.get("asks") else "false"
            sections.append(
                f'  <article class="card" id="skill-{s.get("name")}" '
                f'data-gate="{gate_attr}" data-search="{esc(haystack)}">'
            )
            sections.append('    <div class="head">')
            sections.append(f'      <h3>{s.get("name")}</h3>')
            sections.append('      <span class="badge auto">auto-invocable</span>')
            if gate.get("asks"):
                sections.append('      <span class="badge gate">stops and asks</span>')
            if score:
                sections.append(f'      <span class="score">{esc(score)}</span>')
            sections.append("    </div>")
            sections.append(f'    <p class="summary">{esc(s.get("summary"))}</p>')
            sections.append('    <div class="cols">')
            sections.append('      <div class="pos"><h4>When to use it</h4><ul>')
            for w in s.get("when") or []:
                sections.append(f"        <li>{esc(w)}</li>")
            sections.append("      </ul></div>")
            sections.append('      <div class="neg"><h4>When not to use it</h4><ul>')
            for n in s.get("notWhen") or []:
                sections.append(f"        <li>{esc(n)}</li>")
            sections.append("      </ul></div>")
            sections.append("    </div>")
            sections.append(f'    <div class="ex"><h4>How to use it</h4><p>{esc(s.get("example"))}</p></div>')
            gate_cls = "" if gate.get("asks") else ' class="no"'
            gate_word = "Stops and asks:" if gate.get("asks") else "Does not interrupt:"
            sections.append(f'    <p class="gateline"><b{gate_cls}>{esc(gate_word)}</b> {esc(gate.get("what"))}</p>')
            sections.append("  </article>")
        sections.append("</section>")

    # The template puts {{PHASE_SECTIONS}} on the same line as <main class="wrap">,
    # exactly as the original here-string did; the sections start on a fresh line.
    page = template.replace("{{STAT_ITEMS}}", stat_items).replace(
        "{{PHASE_SECTIONS}}", "\n" + "\n".join(sections)
    )

    out_path = hub_root / args.out_file
    C.write_text(out_path, page)

    size = C.ps_round(out_path.stat().st_size / 1024, 1)
    print(f"wrote {out_path} ({C.ps_num(size)} KB, {len(data)} skills, "
          f"{gate_count} with a stop-and-ask gate)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
