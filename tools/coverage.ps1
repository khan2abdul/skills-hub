#!/usr/bin/env pwsh
# Writes COVERAGE.md: every upstream skill in every cloned repo, and whether the
# hub shipped it, rejected it, or dropped it with no decision.
#
# Truth comes from skills/<name>/PROVENANCE.md, not from manifest candidates.
# A losing candidate was never shipped, so counting it as coverage is how the
# hub looked complete while 72 upstream skills had no home.
#
#   coverage.ps1            -> write COVERAGE.md
#   coverage.ps1 -WhatIf    -> print the summary, write nothing
#   coverage.ps1 -RouterFile ~/.dsh/AGENTS.md
#                           -> also check an always-on router outside the hub
param([switch]$WhatIf, [string]$RouterFile = '')
$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot '_common.ps1')

$hub = Get-HubRoot
$cov = Get-SkillCoverage
$rows = $cov.rows
if (-not $rows) {
  Write-Host "no source repos indexed - run tools/clone-repos.ps1 first" -ForegroundColor Red
  exit 2
}

# Names the always-on router promises. A name here that the hub does not ship is
# a broken promise the agent will hit on the next request, so surface it.
function Get-RouterNames([string]$file) {
  if (-not $file -or -not (Test-Path $file)) { return @() }
  @([regex]::Matches((Get-Content $file -Raw), '`([a-z][a-z0-9]+(-[a-z0-9]+)+)`') |
    ForEach-Object { $_.Groups[1].Value } |
    Where-Object { $_ -notmatch '^(node|npm|pnpm|git|powershell|pwsh|bash)$' } |
    Sort-Object -Unique)
}
$shippedNames = @($cov.shipped.Values | Sort-Object -Unique)
$repoNames = @($rows | ForEach-Object { $_.repo } | Sort-Object -Unique)
$routerFiles = @(Join-Path $hub 'MASTER_ROUTING.md')
if ($RouterFile) { $routerFiles += $RouterFile }
$brokenRouter = @()
foreach ($f in $routerFiles) {
  if (-not (Test-Path $f)) { continue }
  foreach ($n in (Get-RouterNames $f)) {
    # a router name is only safe when a PROVENANCE.md proves it is shipped -
    # either as that exact canonical name, or under the canonical name it became.
    # Existing in repos/ is not enough: repos/ is not an installed skill root.
    if ($repoNames -contains $n) { continue }
    if ($shippedNames -notcontains $n -and -not $cov.shipped.ContainsKey($n)) {
      $reason = if ($cov.index.ContainsKey($n)) { 'upstream only, not shipped' } else { 'no upstream skill' }
      $brokenRouter += "$n  ($reason)"
    }
  }
}

$byRepo = $rows | Group-Object repo | Sort-Object Name
$tot = @($rows).Count
$totShipped = @($rows | Where-Object state -eq 'shipped').Count
$totIgnored = @($rows | Where-Object state -eq 'ignored').Count
$totDropped = @($rows | Where-Object state -eq 'dropped').Count

$sb = New-Object System.Text.StringBuilder
function W([string]$s = '') { [void]$sb.AppendLine($s) }

W '# Coverage'
W ''
W 'Which upstream skill landed where, which were rejected, and which were'
W 'dropped with no decision. Generated by `tools/coverage.ps1` from'
W '`skills/*/PROVENANCE.md` - do not edit by hand; re-run the tool.'
W ''
W "**$tot upstream skills** - $totShipped shipped - $totIgnored rejected in" 
W "``ignore.txt`` - $totDropped dropped with no recorded decision."
W ''
W 'A skill counts as shipped only when a `PROVENANCE.md` names it. A skill that'
W 'appears merely in a manifest `candidates` list was proposed and lost, so it is'
W 'not coverage.'
W ''
W '## By repo'
W ''
W '| repo | upstream | shipped | rejected | dropped | shipped % |'
W '|---|---|---|---|---|---|'
foreach ($g in $byRepo) {
  $s = @($g.Group | Where-Object state -eq 'shipped').Count
  $i = @($g.Group | Where-Object state -eq 'ignored').Count
  $d = @($g.Group | Where-Object state -eq 'dropped').Count
  $pct = [math]::Round(100 * $s / $g.Count)
  W "| $($g.Name) | $($g.Count) | $s | $i | $d | $pct% |"
}
W "| **total** | **$tot** | **$totShipped** | **$totIgnored** | **$totDropped** | **$([math]::Round(100 * $totShipped / $tot))%** |"
W ''

W '## Where each shipped skill came from'
W ''
W 'Read this when a repo looks unused: its content is here under a canonical name.'
W ''
W '| canonical | upstream | repo | upstream chars |'
W '|---|---|---|---|'
foreach ($r in ($rows | Where-Object state -eq 'shipped' | Sort-Object canonical, repo)) {
  W "| ``$($r.canonical)`` | ``$($r.skill)`` | $($r.repo) | $($r.chars) |"
}
W ''

if ($brokenRouter.Count -gt 0) {
  W '## Broken router promises'
  W ''
  W 'An always-on router names these skills, but the hub does not ship them, so'
  W 'the agent cannot load them. Either ship them or remove the line. Checked:'
  W "$(($routerFiles | Where-Object { Test-Path $_ } | ForEach-Object { Split-Path $_ -Leaf }) -join ', ')."
  W ''
  foreach ($n in $brokenRouter) {
    $name, $reason = $n -split '\s{2}\(', 2
    $reason = $reason -replace '\)$', ''
    W "- ``$name`` - $reason"
  }
  W ''
}

W '## Dropped: no shipped body, no rejection reason'
W ''
W 'These are the gap. Each needs one of three decisions: ship it, merge its'
W 'content into an existing skill, or add it to `ignore.txt` with a reason.'
W ''
foreach ($g in ($rows | Where-Object state -eq 'dropped' | Group-Object repo | Sort-Object Name)) {
  W "### $($g.Name) - $($g.Count) dropped"
  W ''
  W '| upstream | chars | proposed for | note |'
  W '|---|---|---|---|'
  foreach ($r in ($g.Group | Sort-Object chars -Descending)) {
    $for = if ($r.claimedBy) { "``$($r.claimedBy)``" } else { '-' }
    $note = if ($routerNames -contains $r.skill) { '**named in MASTER_ROUTING**' }
            elseif ($r.chars -ge 10000) { 'large - likely the better base' }
            else { '' }
    W "| ``$($r.skill)`` | $($r.chars) | $for | $note |"
  }
  W ''
}

W '## Rejected'
W ''
W 'Listed in `ignore.txt`; reasons are in the `manifest.yml` exclusion notes.'
W ''
W '| upstream | repo | chars |'
W '|---|---|---|'
foreach ($r in ($rows | Where-Object state -eq 'ignored' | Sort-Object repo, skill)) {
  W "| ``$($r.skill)`` | $($r.repo) | $($r.chars) |"
}
W ''

$text = $sb.ToString()

# Guard: a coverage file that cannot be trusted is worse than none. Every cloned
# upstream skill must be classified exactly once, or the counts above are wrong.
$seen = @{}
foreach ($r in $rows) {
  if ($seen.ContainsKey($r.skill)) { throw "duplicate upstream name in coverage: $($r.skill)" }
  $seen[$r.skill] = $true
  if ($r.state -notin @('shipped', 'ignored', 'dropped')) { throw "unclassified skill: $($r.skill)" }
}
$sum = $totShipped + $totIgnored + $totDropped
if ($sum -ne $tot) { throw "coverage does not add up: $sum of $tot" }

if ($WhatIf) {
  Write-Host "WOULD write COVERAGE.md ($tot upstream: $totShipped shipped, $totIgnored rejected, $totDropped dropped)" -ForegroundColor Cyan
  if ($brokenRouter.Count -gt 0) { Write-Host "  router names a missing skill: $($brokenRouter -join ', ')" -ForegroundColor Yellow }
  exit 0
}

[System.IO.File]::WriteAllText((Join-Path $hub 'COVERAGE.md'), $text, (New-Object System.Text.UTF8Encoding($false)))
Write-Host "wrote COVERAGE.md" -ForegroundColor Green
Write-Host "  $tot upstream: $totShipped shipped, $totIgnored rejected, $totDropped dropped"
if ($brokenRouter.Count -gt 0) { Write-Host "  router names a missing skill: $($brokenRouter -join ', ')" -ForegroundColor Yellow }
if ($totDropped -gt 0) { Write-Host "  $totDropped dropped skills still need a decision - see Gaps in COVERAGE.md" -ForegroundColor Yellow }
exit 0
