#!/usr/bin/env python3
"""Writes COVERAGE.md: every upstream skill in every cloned repo, and whether the
hub shipped it, rejected it, or dropped it with no decision.

Port of tools/coverage.ps1.

Truth comes from skills/<name>/PROVENANCE.md, not from manifest candidates. A
losing candidate was never shipped, so counting it as coverage is how the hub
looked complete while 72 upstream skills had no home.
"""
from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import hubcommon as C  # noqa: E402

RED, GREEN, YELLOW, CYAN, RESET = "\033[31m", "\033[32m", "\033[33m", "\033[36m", "\033[0m"

NON_SKILL_REFS = {"node", "npm", "pnpm", "git", "powershell", "pwsh", "bash"}

STATES = ("shipped", "ignored", "dropped")


def get_router_names(file: str | Path | None) -> list[str]:
    """Backticked kebab-case names a router promises."""
    if not file or not Path(file).is_file():
        return []
    text = C.read_text(file)
    names = re.findall(r'`([a-z][a-z0-9]+(?:-[a-z0-9]+)+)`', text)
    return sorted({n for n in names if n not in NON_SKILL_REFS})


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--what-if", action="store_true")
    ap.add_argument("--router-file", default="")
    args = ap.parse_args(argv)

    hub = C.get_hub_root()
    cov = C.get_skill_coverage()
    rows = cov["rows"]
    if not rows:
        print(f"{RED}no source repos indexed - run tools/clone_repos.py first{RESET}")
        return 2

    shipped_names = sorted(set(cov["shipped"].values()))
    repo_names = sorted({r["repo"] for r in rows})
    router_files = [hub / "MASTER_ROUTING.md"]
    if args.router_file:
        router_files.append(Path(args.router_file))

    # Every name any router promises. The original collected these per-file inside
    # the broken-promise loop and then referenced an undefined $routerNames when
    # annotating dropped skills, so the "named in MASTER_ROUTING" note could never
    # match a skill the router actually names.
    router_names: set[str] = set()
    broken_router: list[str] = []
    for f in router_files:
        if not Path(f).is_file():
            continue
        for n in get_router_names(f):
            router_names.add(n)
            # a router name is only safe when a PROVENANCE.md proves it is shipped -
            # either as that exact canonical name, or under the canonical name it became.
            if n in repo_names:
                continue
            if n not in shipped_names and n not in cov["shipped"]:
                reason = "upstream only, not shipped" if n in cov["index"] else "no upstream skill"
                broken_router.append(f"{n}  ({reason})")

    by_repo: dict[str, list[dict]] = {}
    for r in rows:
        by_repo.setdefault(r["repo"], []).append(r)
    tot = len(rows)
    tot_shipped = sum(1 for r in rows if r["state"] == "shipped")
    tot_ignored = sum(1 for r in rows if r["state"] == "ignored")
    tot_dropped = sum(1 for r in rows if r["state"] == "dropped")

    out: list[str] = []

    def W(s: str = "") -> None:
        out.append(s)

    W("# Coverage")
    W("")
    W("Which upstream skill landed where, which were rejected, and which were")
    W("dropped with no decision. Generated by `tools/coverage.py` from")
    W("`skills/*/PROVENANCE.md` - do not edit by hand; re-run the tool.")
    W("")
    W(f"**{tot} upstream skills** - {tot_shipped} shipped - {tot_ignored} rejected in")
    W(f"`ignore.txt` - {tot_dropped} dropped with no recorded decision.")
    W("")
    W("A skill counts as shipped only when a `PROVENANCE.md` names it. A skill that")
    W("appears merely in a manifest `candidates` list was proposed and lost, so it is")
    W("not coverage.")
    W("")
    W("## By repo")
    W("")
    W("| repo | upstream | shipped | rejected | dropped | shipped % |")
    W("|---|---|---|---|---|---|")
    for repo in sorted(by_repo):
        group = by_repo[repo]
        s = sum(1 for r in group if r["state"] == "shipped")
        i = sum(1 for r in group if r["state"] == "ignored")
        d = sum(1 for r in group if r["state"] == "dropped")
        # [math]::Round is banker's rounding, which Python's round() also is.
        pct = C.ps_round(100 * s / len(group))
        W(f"| {repo} | {len(group)} | {s} | {i} | {d} | {pct}% |")
    W(f"| **total** | **{tot}** | **{tot_shipped}** | **{tot_ignored}** | **{tot_dropped}** | **{C.ps_round(100 * tot_shipped / tot)}%** |")
    W("")

    W("## Where each shipped skill came from")
    W("")
    W("Read this when a repo looks unused: its content is here under a canonical name.")
    W("")
    W("| canonical | upstream | repo | upstream chars |")
    W("|---|---|---|---|")
    for r in sorted((r for r in rows if r["state"] == "shipped"), key=lambda r: (r["canonical"], r["repo"])):
        W(f"| `{r['canonical']}` | `{r['skill']}` | {r['repo']} | {r['chars']} |")
    W("")

    if broken_router:
        W("## Broken router promises")
        W("")
        W("An always-on router names these skills, but the hub does not ship them, so")
        W("the agent cannot load them. Either ship them or remove the line. Checked:")
        checked = ", ".join(Path(f).name for f in router_files if Path(f).is_file())
        W(f"{checked}.")
        W("")
        for n in broken_router:
            name, reason = n.split("  (", 1)
            W(f"- `{name}` - {reason.rstrip(')')}")
        W("")

    W("## Dropped: no shipped body, no rejection reason")
    W("")
    W("These are the gap. Each needs one of three decisions: ship it, merge its")
    W("content into an existing skill, or add it to `ignore.txt` with a reason.")
    W("")
    dropped_by_repo: dict[str, list[dict]] = {}
    for r in rows:
        if r["state"] == "dropped":
            dropped_by_repo.setdefault(r["repo"], []).append(r)
    for repo in sorted(dropped_by_repo):
        group = dropped_by_repo[repo]
        W(f"### {repo} - {len(group)} dropped")
        W("")
        W("| upstream | chars | proposed for | note |")
        W("|---|---|---|---|")
        for r in sorted(group, key=lambda r: -r["chars"]):
            for_ = f"`{r['claimedBy']}`" if r.get("claimedBy") else "-"
            if r["skill"] in router_names:
                note = "**named in MASTER_ROUTING**"
            elif r["chars"] >= 10000:
                note = "large - likely the better base"
            else:
                note = ""
            W(f"| `{r['skill']}` | {r['chars']} | {for_} | {note} |")
        W("")

    W("## Rejected")
    W("")
    W("Listed in `ignore.txt`; reasons are in the `manifest.yml` exclusion notes.")
    W("")
    W("| upstream | repo | chars |")
    W("|---|---|---|")
    for r in sorted((r for r in rows if r["state"] == "ignored"), key=lambda r: (r["repo"], r["skill"])):
        W(f"| `{r['skill']}` | {r['repo']} | {r['chars']} |")
    W("")

    # Guard: a coverage file that cannot be trusted is worse than none. Every
    # cloned upstream skill must be classified exactly once, or the counts are wrong.
    seen = set()
    for r in rows:
        if r["skill"] in seen:
            raise ValueError(f"duplicate upstream name in coverage: {r['skill']}")
        seen.add(r["skill"])
        if r["state"] not in STATES:
            raise ValueError(f"unclassified skill: {r['skill']}")
    total = tot_shipped + tot_ignored + tot_dropped
    if total != tot:
        raise ValueError(f"coverage does not add up: {total} of {tot}")

    if args.what_if:
        print(f"{CYAN}WOULD write COVERAGE.md ({tot} upstream: {tot_shipped} shipped, {tot_ignored} rejected, {tot_dropped} dropped){RESET}")
        if broken_router:
            print(f"  {YELLOW}router names a missing skill: {', '.join(broken_router)}{RESET}")
        return 0

    C.write_text(hub / "COVERAGE.md", "\n".join(out) + "\n")
    print(f"{GREEN}wrote COVERAGE.md{RESET}")
    print(f"  {tot} upstream: {tot_shipped} shipped, {tot_ignored} rejected, {tot_dropped} dropped")
    if broken_router:
        print(f"  {YELLOW}router names a missing skill: {', '.join(broken_router)}{RESET}")
    if tot_dropped:
        print(f"  {YELLOW}{tot_dropped} dropped skills still need a decision - see Gaps in COVERAGE.md{RESET}")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except ValueError as e:
        print(f"{RED}{e}{RESET}", file=sys.stderr)
        sys.exit(1)
