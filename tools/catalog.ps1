#!/usr/bin/env pwsh
# Writes SKILLS.md: what every shipped skill does, where it came from, and -
# for compositions - exactly which upstream sections were combined.
#
# Sources of truth, in order: manifest.yml for the capability, PROVENANCE.md
# for the origin and excerpts, SKILL.md for the description, RATING.json for
# the current score. Nothing here is hand-maintained.
param([switch]$WhatIf)
$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot '_common.ps1')
. (Join-Path $PSScriptRoot '_rubric.ps1')

$hub = Get-HubRoot
$skillsDir = Join-Path $hub 'skills'
$loaded = Read-Repos (Join-Path $hub 'repos.toml')
$index = Get-SkillIndex $loaded.repos

$scores = @{}
$ratingFile = Join-Path $hub 'RATING.json'
if (Test-Path $ratingFile) {
  $rating = Get-Content $ratingFile -Raw | ConvertFrom-Json
  foreach ($r in $rating.skills) { $scores[$r.name] = $r.score }
}

# The order a reader meets the skills, not alphabetical.
$phases = [ordered]@{
  'Understand' = @('interview-me-properly','discuss-on-new-idea','explore-this-repo','research-this-topic')
  'Define'     = @('write-the-spec','write-the-domain-glossary','design-the-interface','document-the-decision','write-the-docs')
  'Plan'       = @('break-into-tasks','review-the-plan','set-the-quality-bar')
  'Build'      = @('build-it-test-first','build-in-small-steps','write-less-code','simplify-this-code','split-across-agents','isolate-this-branch')
  'Finish'     = @('finish-the-experience')
  'Debug'      = @('debug-this-code','debug-the-stubborn-one','fix-this-bug')
  'Review'     = @('review-my-code','receive-code-review','check-my-security','audit-the-whole-repo','prove-it-works','test-every-surface')
  'UI'         = @('check-my-ui','polish-the-ui','make-it-accessible','make-it-fast')
  'Operate'    = @('make-it-observable','ship-it','guard-the-dangerous-stuff','hand-off-to-next-session')
  'Meta'       = @('watch-my-context','trim-my-output','route-to-the-right-skill','write-a-new-skill','deslop-the-writing')
}

function Clean-Section([string]$s) {
  $s = $s.Trim()
  if ($s -like 'file:*') { $s = $s.Substring(5) -replace '#', ': ' }
  $out = ($s -replace '^#+\s*', '').Trim()
  if (-not $out) { 'whole body' } else { $out }
}

$rows = @()
foreach ($d in (Get-ChildItem $skillsDir -Directory | Sort-Object Name)) {
  $file = Join-Path $d.FullName 'SKILL.md'
  if (-not (Test-Path $file)) { continue }
  $text = [System.IO.File]::ReadAllText($file)
  $fm = Get-Frontmatter $text
  $desc = $fm.keys['description']
  if (-not $desc) { $desc = '(no description)' }

  $provFile = Join-Path $d.FullName 'PROVENANCE.md'
  $prov = if (Test-Path $provFile) { [System.IO.File]::ReadAllText($provFile) } else { '' }
  $mode = ([regex]::Match($prov, '(?m)^- mode:\s*(.+?)\s*$')).Groups[1].Value
  $upstream = ([regex]::Match($prov, '(?m)^- upstream:\s*(.+?)\s*$')).Groups[1].Value
  $repo = ([regex]::Match($prov, '(?m)^- repo:\s*(.+?)\s*$')).Groups[1].Value

  $build = @()
  if ($mode -eq 'composed') {
    $grouped = [ordered]@{}
    foreach ($m in [regex]::Matches($prov, '(?m)^\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*[0-9a-f]{64}\s*\|\s*([0-9]+)\s*\|')) {
      $src = $m.Groups[1].Value.Trim()
      $sec = Clean-Section $m.Groups[2].Value
      if (-not $grouped.Contains($src)) { $grouped[$src] = @() }
      $grouped[$src] += $sec
    }
    foreach ($src in $grouped.Keys) {
      $srcRepo = if ($index.ContainsKey($src)) { $index[$src].repo } else { 'unknown' }
      $build += [pscustomobject]@{ skill = $src; repo = $srcRepo; sections = @($grouped[$src]) }
    }
  }

  $rows += [pscustomobject]@{
    name = $d.Name
    description = $desc
    mode = $mode
    upstream = $upstream
    repo = $repo
    build = @($build)
    chars = $text.Length
    score = $scores[$d.Name]
  }
}

$byName = @{}
foreach ($r in $rows) { $byName[$r.name] = $r }
$verbatim = @($rows | Where-Object { $_.mode -eq 'verbatim' }).Count
$composed = @($rows | Where-Object { $_.mode -eq 'composed' }).Count

$sb = New-Object System.Text.StringBuilder
function W([string]$s = '') { [void]$sb.AppendLine($s) }

W '# Skill catalog'
W ''
W 'What each shipped skill does, which upstream repo and skill it came from,'
W 'and - for composed skills - exactly which sections were combined.'
W ''
W 'Generated by `tools/catalog.ps1` from `manifest.yml`,'
W '`skills/*/PROVENANCE.md`, each `SKILL.md`, and `RATING.json`. Do not edit by'
W 'hand. Exact commits and per-block sha256 are in `skills/<name>/PROVENANCE.md`.'
W ''
W "**$($rows.Count) skills: $verbatim verbatim copies, $composed compositions.**"
W ''

$mapped = @()
foreach ($phase in $phases.Keys) {
  $names = @($phases[$phase] | Where-Object { $byName.ContainsKey($_) })
  if (-not $names.Count) { continue }
  $mapped += $names
  W "## $phase"
  W ''
  foreach ($name in $names) {
    $r = $byName[$name]
    W "### ``$name``"
    W ''
    W "**What it does:** $($r.description)"
    W ''
    if ($r.mode -eq 'composed') {
      W "**Built from $($r.build.Count) upstream skills:**"
      W ''
      foreach ($b in $r.build) {
        W "- ``$($b.skill)`` (``$($b.repo)``): $($b.sections -join '; ')"
      }
      W ''
      W "**Compose spec:** ``compose/$name.yml``"
    } elseif ($r.mode -eq 'verbatim') {
      W "**Source:** ``$($r.repo)`` / ``$($r.upstream)`` - verbatim, name line only"
    } else {
      W "**Source:** no PROVENANCE.md"
    }
    W ''
    $score = if ($null -ne $r.score) { "$($r.score)/10" } else { 'unrated' }
    W "**Size:** $($r.chars) chars | **Score:** $score | **Provenance:** ``skills/$name/PROVENANCE.md``"
    W ''
  }
}

$other = @($rows | Where-Object { $mapped -notcontains $_.name } | ForEach-Object { $_.name })
if ($other.Count) {
  W '## Other'
  W ''
  foreach ($name in ($other | Sort-Object)) {
    $r = $byName[$name]
    W "### ``$name``"
    W ''
    W "**What it does:** $($r.description)"
    W ''
    $srcLabel = if ($r.mode -eq 'composed') { 'composed' } else { "``$($r.repo)`` / ``$($r.upstream)``" }
    W "**Source:** $srcLabel"
    W ''
  }
}

W '## Source repos'
W ''
W '| repo | URL |'
W '|---|---|'
foreach ($r in ($loaded.repos | Where-Object { $_.status -eq 'cloned' } | Sort-Object { [string]$_.name })) {
  W "| ``$($r.name)`` | $($r.url) |"
}
W ''
W 'A verbatim skill is an unmodified copy: only the frontmatter `name:` line'
W 'changes. A composition quotes named sections byte-for-byte and records their'
W 'sha256. `tools/verify.ps1` re-extracts and re-hashes every block.'
W ''

if ($WhatIf) {
  Write-Host "WOULD write SKILLS.md ($($rows.Count) skills: $verbatim verbatim, $composed composed)"
  exit 0
}

[System.IO.File]::WriteAllText((Join-Path $hub 'SKILLS.md'), $sb.ToString(), (New-Object System.Text.UTF8Encoding($false)))
Write-Host "wrote SKILLS.md" -ForegroundColor Green
Write-Host "  $($rows.Count) skills: $verbatim verbatim, $composed composed"
exit 0
